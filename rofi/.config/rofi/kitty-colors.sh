#!/usr/bin/env bash
# Write ~/.config/rofi/colors.rasi from kitty's current colors, so every rofi
# popup matches the kitty (and emacs) theme. Run by theme-select.
conf="$HOME/.config/kitty/current-theme.conf"
out="$HOME/.config/rofi/colors.rasi"

get() {  # get KEY [FALLBACK-KEY...]: the first of these kitty colors that is set
    local k v
    for k in "$@"; do
        v="$(awk -v k="$k" '$1==k && $2 ~ /^#[0-9a-fA-F]{6}$/ {print $2; exit}' "$conf")"
        [ -n "$v" ] && { echo "$v"; return; }
    done
}

bg="$(get background)";                 bg="${bg:-#282828}"
fg="$(get foreground)";                 fg="${fg:-#ebdbb2}"
cat > "$out.tmp" <<RASI
/* Generated by kitty-colors.sh from kitty's current theme; edits are overwritten */
* {
    bg:      $bg;
    fg:      $fg;
    alt-bg:  $(get inactive_tab_background color0);
    dim:     $(get inactive_tab_foreground color8);
    sel-bg:  $(get selection_background color3);
    sel-fg:  $(get selection_foreground background);
    accent:  $(get cursor color4);
    urgent:  $(get color1);
    frame:   $fg;
}
RASI
mv "$out.tmp" "$out"
