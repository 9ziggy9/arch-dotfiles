#!/usr/bin/env python3
"""Make the status bar's colors from kitty's current theme.

Writes, from ~/.config/kitty/current-theme.conf:
  - themes/kitty-powerline.json: a bumblebee-status theme laid out like
    solarized-powerline (segments alternating between the background and a
    lighter shade of it, powerline arrows between), in the theme's colors
  - colors.json: background, text and frame colors for statusline.py
  - ~/.config/i3/bar.conf, the i3bar block, from the bar.conf.in template

Run by theme-select; the bar has to restart to pick the new colors up.
"""
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
KITTY = os.path.expanduser("~/.config/kitty/current-theme.conf")
I3_BAR_TEMPLATE = os.path.expanduser("~/.config/i3/bar.conf.in")
I3_BAR = os.path.expanduser("~/.config/i3/bar.conf")
HEX = re.compile(r"#[0-9a-fA-F]{6}")

kitty = {}
try:
    with open(KITTY) as f:
        for line in f:
            parts = line.split()
            if len(parts) >= 2 and HEX.fullmatch(parts[1]):
                kitty[parts[0]] = parts[1].lower()
except OSError:
    pass

defaults = {  # gruvbox, for anything the kitty theme leaves out
    "background": "#282828", "foreground": "#ebdbb2",
    "color1": "#cc241d", "color2": "#98971a", "color3": "#d79921",
    "color5": "#b16286", "color6": "#689d6a",
}
c = {**defaults, **kitty}


def rgb(h):
    return [int(h[i:i + 2], 16) for i in (1, 3, 5)]


def mix(a, b, frac):
    """a with frac of b mixed in."""
    return "#" + "".join(f"{round(x + frac * (y - x)):02x}" for x, y in zip(rgb(a), rgb(b)))


def dark(h):
    r, g, b = rgb(h)
    return 0.2126 * r + 0.7152 * g + 0.0722 * b < 128


bg, fg = c["background"], c["foreground"]
# the second segment colour: like solarized's base01 on base03, a shade
# between background and text, with text a step brighter than usual
alt_bg = mix(bg, fg, 0.3)
alt_fg = mix(fg, "#ffffff" if dark(bg) else "#000000", 0.5)
warn = {"fg": bg, "bg": c["color3"]}
crit = {"fg": bg, "bg": c["color1"]}
good = {"fg": bg, "bg": c["color2"]}

theme = {
    "icons": ["awesome-fonts"],
    "defaults": {"separator-block-width": 0, "warning": warn, "critical": crit},
    "cycle": [{"fg": fg, "bg": bg}, {"fg": alt_fg, "bg": alt_bg}],
    "dnf": {"good": good},
    "pacman": {"good": good},
    "apt": {"good": good},
    "battery": {"charged": good, "AC": good},
    "git": {"modified": {"bg": c["color6"]}, "deleted": {"bg": c["color5"]}, "new": {"bg": c["color2"]}},
    "pomodoro": {"paused": warn, "work": {"fg": alt_fg, "bg": alt_bg}, "break": good},
}

os.makedirs(os.path.join(HERE, "themes"), exist_ok=True)
with open(os.path.join(HERE, "themes", "kitty-powerline.json"), "w") as f:
    json.dump(theme, f, indent=2)
with open(os.path.join(HERE, "colors.json"), "w") as f:
    json.dump({"bg": bg, "fg": fg, "frame": fg}, f, indent=2)

# i3 doesn't pass variables from included files back to the main config, so
# the whole bar block is generated and ~/.config/i3/config includes it
with open(I3_BAR_TEMPLATE) as f:
    text = f.read().replace("@background@", bg).replace("@statusline@", fg)
with open(I3_BAR + ".tmp", "w") as f:
    f.write("# Generated by bar-theme.py from bar.conf.in; edits are overwritten\n" + text)
os.replace(I3_BAR + ".tmp", I3_BAR)
